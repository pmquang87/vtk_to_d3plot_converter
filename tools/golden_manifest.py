"""Golden test data checksum manifest - detect silent drift in test fixtures.

Usage:
    # Generate/update manifest:
    .venv\\Scripts\\python.exe tools\\golden_manifest.py generate

    # Verify golden data against manifest:
    .venv\\Scripts\\python.exe tools\\golden_manifest.py verify

    # Another data tree (a copy of tests/data) or another manifest file:
    .venv\\Scripts\\python.exe tools\\golden_manifest.py verify --root <dir> --manifest <file>

Line-ending rule (text vs binary):
    A file is TEXT when its name does not match a binary pattern
    (``*.d3plot``, ``*.d3plotNN``, ``*.png``) and its content holds no NUL byte.
    TEXT files are hashed and sized with every CRLF normalised to LF - the form
    git stores - so the manifest verifies on an LF checkout (Linux/macOS CI)
    and on a CRLF checkout (Windows, core.autocrlf=true) alike. All other files
    (d3plot families, binary ANIM files) are hashed and sized raw.

Verify fails (exit code 1) on any MISSING, CHANGED, SIZE or NEW file or BAD
LINE. NEW files (on disk, not in the manifest) count as errors, so an added
fixture or a truncated manifest cannot pass. A file that is both CHANGED and
SIZE is one mismatch. Legacy lines without a size (``<sha>  <path>``) are
still read; paths may contain double spaces.

``generate`` hashes every file before it writes anything and then replaces the
manifest atomically, so a failure part-way leaves the old manifest unchanged.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA_DIR = REPO / "tests" / "data"
MANIFEST_NAME = "MANIFEST.sha256"
MANIFEST_PATH = DATA_DIR / "golden" / MANIFEST_NAME

# Directories to checksum, relative to the data root
GOLDEN_SUBDIRS = ["golden", "port_dialect"]

SKIP_EXTENSIONS = {".pyc", ".pyo", ".log", ".tmp"}

# LS-PrePost scratch files (lspost.db, lspost.msg, ...). LS-PrePost writes them
# next to a d3plot it opens; a run that crashes or times out leaves them behind.
# They are never fixtures, so they are neither hashed nor reported as NEW.
SKIP_NAME_RE = re.compile(r"^lspost\.", re.IGNORECASE)

# Names that are always binary, whatever their content.
BINARY_NAME_RE = re.compile(r"\.(d3plot(\d+)?|png)$", re.IGNORECASE)

MANIFEST_HEADER = (
    "# vtk2d3plot golden-fixture manifest. Format: <sha256>  <size>  <path relative to tests/data>\n"
    "# Generated by tools/golden_manifest.py generate - do not edit by hand.\n"
    "# Text rule: a file is TEXT if its name is not *.d3plot / *.d3plotNN / *.png and it holds\n"
    "# no NUL byte. TEXT files are hashed and sized with CRLF normalised to LF (git's stored\n"
    "# form), so LF and CRLF checkouts verify alike. All other files are hashed raw.\n"
)


def is_text(filepath: Path, data: bytes) -> bool:
    """True if ``filepath`` is a text fixture (see the module docstring)."""
    if BINARY_NAME_RE.search(filepath.name):
        return False
    return b"\x00" not in data


def canonical_bytes(filepath: Path) -> bytes:
    """File content in manifest form: CRLF->LF for text files, raw for binary files."""
    data = filepath.read_bytes()
    if is_text(filepath, data):
        return data.replace(b"\r\n", b"\n")
    return data


def compute_sha256(filepath: Path) -> str:
    """SHA-256 of the manifest form of the file (see ``canonical_bytes``)."""
    return hashlib.sha256(canonical_bytes(filepath)).hexdigest()


def hash_and_size(filepath: Path) -> tuple[str, int]:
    data = canonical_bytes(filepath)
    return hashlib.sha256(data).hexdigest(), len(data)


def _collect_files(root: Path = DATA_DIR) -> list[Path]:
    files = []
    for sub in GOLDEN_SUBDIRS:
        d = root / sub
        if d.exists():
            for f in sorted(d.rglob("*")):
                if (
                    f.is_file()
                    and f.suffix not in SKIP_EXTENSIONS
                    and f.name != MANIFEST_NAME
                    and not SKIP_NAME_RE.match(f.name)
                ):
                    files.append(f)
    return files


def generate(root: Path = DATA_DIR, manifest: Path | None = None) -> int:
    """Write the manifest for ``root``.

    Every file is hashed first; only then is the manifest written, to a temp
    file in the same folder that replaces the old manifest in one step. An
    error or Ctrl+C part-way leaves the old manifest unchanged.
    """
    manifest = manifest or root / "golden" / MANIFEST_NAME
    files = _collect_files(root)
    lines = [MANIFEST_HEADER]
    for filepath in files:
        rel_path = filepath.relative_to(root).as_posix()
        sha, size = hash_and_size(filepath)
        lines.append(f"{sha}  {size}  {rel_path}\n")
    fd, tmp = tempfile.mkstemp(prefix=manifest.name + ".", suffix=".tmp", dir=manifest.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as out:
            out.writelines(lines)
        os.replace(tmp, manifest)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    print(f"Generated manifest with {len(files)} files -> {manifest}")
    return len(files)


# Manifest lines: "<sha>  <size>  <path>" (current) or "<sha>  <path>" (legacy).
# The path is the rest of the line and may itself hold double spaces. A legacy
# path that is all digits followed by two spaces would read as a size; manifest
# paths start with golden/ or port_dialect/, so that cannot happen.
_LINE_RE = re.compile(r"^([0-9a-fA-F]{64})  (?:(\d+)  )?(.+)$")


def verify(root: Path = DATA_DIR, manifest: Path | None = None) -> int:
    """Check the data tree against the manifest. Returns the number of errors."""
    manifest = manifest or root / "golden" / MANIFEST_NAME
    if not manifest.exists():
        print("ERROR: Manifest file not found. Run 'generate' first.")
        return 1

    errors = 0
    checked = 0
    manifest_entries = set()
    with manifest.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line.strip() or line.startswith("#"):
                continue
            m = _LINE_RE.match(line)
            if m is None:
                print(f"  BAD LINE: {line!r}")
                errors += 1
                continue
            expected_sha, size_text, rel_path = m.groups()
            expected_size = None if size_text is None else int(size_text)  # None: legacy line
            manifest_entries.add(rel_path)
            filepath = root / rel_path
            if not filepath.exists():
                print(f"  MISSING: {rel_path}")
                errors += 1
            else:
                actual_sha, actual_size = hash_and_size(filepath)
                bad = False
                if actual_sha != expected_sha.lower():
                    print(f"  CHANGED: {rel_path}")
                    bad = True
                if expected_size is not None and actual_size != expected_size:
                    print(f"  SIZE: {rel_path} (expected {expected_size}, got {actual_size})")
                    bad = True
                errors += bad  # one mismatch per file, even with both lines printed
            checked += 1

    # Files on disk that the manifest does not list are errors too: an added
    # fixture (e.g. an extra state file) or a truncated manifest must not pass.
    disk_files = {f.relative_to(root).as_posix() for f in _collect_files(root)}
    new_files = disk_files - manifest_entries
    if new_files:
        print(f"  NEW ({len(new_files)} files not in manifest):")
        for nf in sorted(new_files)[:10]:
            print(f"    {nf}")
        if len(new_files) > 10:
            print(f"    ... and {len(new_files) - 10} more")
        errors += len(new_files)

    if errors == 0:
        print(f"OK: all {checked} golden files match manifest")
    else:
        print(f"FAILED: {errors} mismatches found.")
    return errors


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Manage golden files manifest.")
    parser.add_argument("command", choices=["generate", "verify"], help="Command to run")
    parser.add_argument(
        "--root",
        type=Path,
        default=DATA_DIR,
        help="data root holding golden/ and port_dialect/ (default: tests/data)",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=None,
        help="manifest file (default: <root>/golden/MANIFEST.sha256)",
    )
    args = parser.parse_args(argv)

    if args.command == "generate":
        generate(args.root, args.manifest)
        return 0
    return 0 if verify(args.root, args.manifest) == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
